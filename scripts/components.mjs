#!/usr/bin/env node
// Components: project/components/<group>/<name>.{css,md,examples.html}
//   - writes project/components.css (all component CSS in group order; generated, never edit)
//   - writes dist/components/index.html and one page per component, with live examples
//     rendered side by side in light and dark.
// Run after scripts/site.mjs (npm run build does both).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { marked } from 'marked';
import { inlineIcons, esc } from './lib.mjs';

const ROOT = new URL('..', import.meta.url);
const SRC = new URL('project/components/', ROOT);
export const GROUPS = [
  ['core', 'Core', 'Logo, icons, type, avatars'],
  ['layout', 'Layout', 'Stack, row, columns and grid: how a screen arranges components'],
  ['actions', 'Actions', 'Buttons, links, menus'],
  ['forms', 'Forms', 'Fields, choices, upload, the form layout'],
  ['status', 'Status', 'Lozenges, badges, tags, progress, loading'],
  ['messages', 'Messages', 'Banners, section and inline messages, flags, empty states, tooltips'],
  ['overlays', 'Overlays', 'Dialogs, drawers, popups'],
  ['navigation', 'Navigation', 'App shell, side and top navigation, tabs, breadcrumbs, pagination, page header'],
  ['data', 'Data', 'Tables, cards, stat cards, description lists, accordions, timelines'],
  ['agent', 'Agent', 'Everything Pepla\'s AI agents show: proposals, marks, panels'],
  ['records', 'HR records', 'People, documents, verification, deadlines, pipeline, approvals, audit'],
];

export function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return [{}, md];
  const meta = Object.fromEntries(m[1].split('\n').map((l) => { const i = l.indexOf(':'); return [l.slice(0, i).trim(), l.slice(i + 1).trim()]; }));
  return [meta, md.slice(m[0].length)];
}

export function loadComponents() {
  const list = [];
  for (const [group] of GROUPS) {
    const dir = new URL(`${group}/`, SRC);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter((x) => x.endsWith('.md')).sort()) {
      const slug = f.slice(0, -3);
      const md = readFileSync(new URL(f, dir), 'utf8');
      const [meta, body] = frontmatter(md);
      const cssPath = new URL(`${slug}.css`, dir);
      const exPath = new URL(`${slug}.examples.html`, dir);
      list.push({
        group, slug, meta, body,
        css: existsSync(cssPath) ? readFileSync(cssPath, 'utf8') : '',
        examples: existsSync(exPath) ? readFileSync(exPath, 'utf8') : '',
        files: { css: existsSync(cssPath), examples: existsSync(exPath) },
      });
    }
  }
  return list;
}

export function bundleCss(list) {
  return `/* Pepla design system: every component's CSS, in group order.\n   GENERATED by scripts/components.mjs from project/components/. Do not edit. */\n\n` +
    list.filter((c) => c.css).map((c) => `/* ---- ${c.group}/${c.slug} ---- */\n${c.css.trim()}\n`).join('\n');
}

