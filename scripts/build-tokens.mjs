#!/usr/bin/env node
// Builds project/tokens/*.css and project/tokens/tokens.json from tokens/ (the source of truth).
//   npm run tokens
// Never edit project/tokens by hand: CI rebuilds them and fails if they differ.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { converter, formatHex, formatHex8, interpolate } from 'culori';
import { light, dark } from '../tokens/semantic.mjs';
import * as F from '../tokens/foundations.mjs';

const ROOT = new URL('..', import.meta.url);
const OUT = new URL('project/tokens/', ROOT);
mkdirSync(OUT, { recursive: true });

export const palette = JSON.parse(readFileSync(new URL('tokens/palette.json', ROOT), 'utf8')).ramps;
const rgb = converter('rgb');

export function resolve(v) {
  v = v.trim();
  let m;
  if ((m = v.match(/^\{(\w+)\.(\d+)\}$/))) {
    const hex = palette[m[1]]?.[m[2]];
    if (!hex) throw new Error(`Unknown palette step ${v}`);
    return hex;
  }
  if ((m = v.match(/^mix\((.+),\s*(.+),\s*(\d+)\)$/))) {
    const a = resolve(m[1]), b = resolve(m[2]);
    return formatHex(interpolate([b, a], 'oklab')(Number(m[3]) / 100));
  }
  if ((m = v.match(/^alpha\((.+),\s*(\d+)\)$/))) {
    const c = rgb(resolve(m[1]));
    return formatHex8({ ...c, alpha: Number(m[2]) / 100 });
  }
  return v; // literal hex or keyword
}

const cssName = (k) => '--' + k.replace(/\./g, '-');
const block = (sel, entries, indent = '  ') => `${sel} {\n${entries.map(([k, v]) => `${indent}${cssName(k)}: ${v};`).join('\n')}\n}\n`;
const HEAD = (what) => `/* Naleko People design system: ${what}.\n   GENERATED by scripts/build-tokens.mjs from tokens/. Do not edit. */\n`;

export function resolvedThemes() {
  const L = Object.fromEntries(Object.entries(light).map(([k, v]) => [k, resolve(v)]));
  const D = Object.fromEntries(Object.entries(dark).map(([k, v]) => [k, resolve(v)]));
  const missing = Object.keys(L).filter((k) => !(k in D));
  const extra = Object.keys(D).filter((k) => !(k in L));
  if (missing.length || extra.length) throw new Error(`Light and dark must define the same tokens. Missing in dark: ${missing.join(', ')}; extra in dark: ${extra.join(', ')}`);
  return { light: L, dark: D };
}

function build() {
  const { light: L, dark: D } = resolvedThemes();
  const files = {};

  // palette
  const pal = [];
  for (const [ramp, steps] of Object.entries(palette)) for (const [s, hex] of Object.entries(steps)) pal.push([`palette.${ramp}.${s}`, hex]);
  files['palette.css'] = HEAD('palette ramps. Components NEVER use these; use the semantic tokens in colors.css') + block(':root', pal);

  // colours: light on :root, dark on [data-theme="dark"], and on prefers-color-scheme unless the page pins light
  const lightEntries = [...Object.entries(L), ...Object.entries(F.shadows.light)];
  const darkEntries = [...Object.entries(D), ...Object.entries(F.shadows.dark)];
  files['colors.css'] = HEAD('semantic colour and elevation tokens, light and dark') +
    block(':root, [data-theme="light"]', lightEntries) + '\n' +
    block('[data-theme="dark"]', darkEntries) + '\n' +
    `@media (prefers-color-scheme: dark) {\n` + block('  :root:not([data-theme="light"])', darkEntries, '    ').replace(/\n}\n$/, '\n  }\n') + `}\n` +
    `\n:root { color-scheme: light; }\n[data-theme="dark"] { color-scheme: dark; }\n@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { color-scheme: dark; } }\n`;

  // typography
  const fam = { display: 'var(--font-family-display)', body: 'var(--font-family-body)', code: 'var(--font-family-code)' };
  const typeVars = [...Object.entries(F.fonts)];
  const classes = [];
  for (const [name, [w, size, line, track, f]] of Object.entries(F.type)) {
    typeVars.push([`font.${name}`, `${w} ${size}px/${line}px ${fam[f]}`]);
    typeVars.push([`font.${name}.tracking`, track]);
    const cls = name.replace(/\./g, '-');
    classes.push(`.pp-text-${cls} { font: var(--font-${cls}); letter-spacing: var(--font-${cls}-tracking);${name.startsWith('metric') ? ' font-variant-numeric: tabular-nums;' : ''}${name === 'label.small' ? ' text-transform: uppercase;' : ''} }`);
  }
  files['typography.css'] = HEAD('type tokens (font shorthand + tracking per style)') + block(':root', typeVars) +
    '\n/* Optional utility classes; components use the variables directly. */\n' + classes.join('\n') + '\n';

  files['spacing.css'] = HEAD('space and layout tokens') + block(':root', [...Object.entries(F.space), ...Object.entries(F.layout)]) +
    `/* Breakpoints (min-width, px), for media queries: ${Object.entries(F.breakpoints).map(([k, v]) => `${k} ${v}`).join(', ')} */\n`;
  files['shape.css'] = HEAD('radius and border tokens') + block(':root', Object.entries(F.shape));
  files['motion.css'] = HEAD('motion tokens') + block(':root', Object.entries(F.motion)) +
    `\n@media (prefers-reduced-motion: reduce) {\n  :root { --motion-duration-fast: 0ms; --motion-duration-medium: 0ms; --motion-duration-slow: 0ms; --motion-scale-pressed: 1; }\n}\n` +
    `\n@keyframes pp-spin { to { transform: rotate(360deg); } }\n@keyframes pp-shimmer { from { opacity: .6; } to { opacity: 1; } }\n`;
  files['layers.css'] = HEAD('stacking order') + block(':root', Object.entries(F.layers));

  // machine-readable copy (W3C design tokens format, resolved), for the PrimeNG preset and other platforms
  const dtcg = (obj, type) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, { $type: type, $value: v }]));
  files['tokens.json'] = JSON.stringify({
    $description: 'Naleko People design tokens, resolved. GENERATED by scripts/build-tokens.mjs. Do not edit.',
    color: { light: dtcg(L, 'color'), dark: dtcg(D, 'color') },
    shadow: { light: dtcg(F.shadows.light, 'shadow'), dark: dtcg(F.shadows.dark, 'shadow') },
    typography: Object.fromEntries(Object.entries(F.type).map(([k, [w, s, l, t, f]]) => [k, { $type: 'typography', $value: { fontFamily: F.fonts[`font.family.${f}`], fontWeight: w, fontSize: `${s}px`, lineHeight: `${l}px`, letterSpacing: t } }])),
    space: dtcg(F.space, 'dimension'), shape: dtcg(F.shape, 'dimension'), layout: dtcg(F.layout, 'dimension'),
    motion: dtcg(F.motion, 'other'), layers: dtcg(F.layers, 'number'), breakpoints: F.breakpoints,
  }, null, 2) + '\n';

  return files;
}

export const files = build();
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  for (const [name, text] of Object.entries(files)) writeFileSync(new URL(name, OUT), text);
  console.log(`Wrote ${Object.keys(files).length} files to project/tokens/`);
}
