#!/usr/bin/env node
// Icon vocabulary as data: writes project/icons.json from the readme's Iconography tables.
// The Angular app syncs this file and checks every <svg ppIcon="…"> against it, so the app and
// this repo share one list. The readme stays the source; never edit icons.json by hand.
//
//   node scripts/icons-json.mjs          (runs in npm run build)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const README = new URL('../project/readme.md', import.meta.url);
const OUT = new URL('../project/icons.json', import.meta.url);

export function vocabulary(readme = readFileSync(README, 'utf8')) {
  const section = readme.split('## Iconography')[1].split('\n## ')[0];
  const icons = [];
  let group = null;
  for (const line of section.split('\n')) {
    const g = line.match(/^\*\*(.+?)\*\*\s*$/);
    if (g) { group = g[1]; continue; }
    const row = line.match(/^\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|\s*$/);
    if (!row || !group || /^-+$/.test(row[1]) || row[1] === 'Meaning') continue;
    for (const [, name] of row[2].matchAll(/`([a-z0-9-]+)`/g)) {
      if (!name.startsWith('-')) icons.push({ name, meaning: row[1], group });
    }
  }
  return icons;
}

export const render = (icons) => `${JSON.stringify({
  source: 'project/readme.md, Iconography. Generated by scripts/icons-json.mjs; do not edit.',
  icons,
}, null, 2)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const icons = vocabulary();
  writeFileSync(OUT, render(icons));
  console.log(`project/icons.json: ${icons.length} icons`);
}
