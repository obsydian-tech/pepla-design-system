#!/usr/bin/env node
// Generates the Pepla palette ramps (tokens/palette.json) from the locked brand colours.
// Each ramp keeps one hue in OKLCH and walks a fixed lightness scale; the brand colour itself
// replaces the step nearest its lightness, so #5b4bd6 is exactly violet-600, and so on.
// Run: npm run palette. Never edit tokens/palette.json by hand.
import { converter, formatHex, clampChroma, wcagContrast } from 'culori';
import { writeFileSync } from 'node:fs';

const oklch = converter('oklch');
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const L = { 50: .975, 100: .945, 200: .895, 300: .825, 400: .74, 500: .655, 600: .565, 700: .48, 800: .395, 900: .31, 950: .235 };
// chroma multiplier per step: tints and shades carry less chroma than the middle
const C = { 50: .18, 100: .32, 200: .55, 300: .8, 400: .95, 500: 1, 600: 1, 700: .92, 800: .82, 900: .7, 950: .6 };

// anchors: [name, seed hex, peak chroma override?, exact brand hexes to pin]
const RAMPS = {
  violet:  { seed: '#5b4bd6', pin: { '#5b4bd6': null, '#7d6ff0': null } },
  coral:   { seed: '#ff7a59', pin: { '#ff7a59': null, '#fff4ef': null } },
  mint:    { seed: '#2bb3a3', pin: { '#2bb3a3': null, '#1e7f74': null } },
  ink:     { seed: '#1b1640', chroma: .05, pin: { '#1b1640': null, '#4a4566': null, '#6b6585': null, '#f3f0f8': null, '#e7e1f2': null, '#d9d3e6': null } },
  red:     { seed: '#cf2350' },
  amber:   { seed: '#d98a00' },
  green:   { seed: '#2f9e4f' },
  blue:    { seed: '#2f6fe0' },
  magenta: { seed: '#c2399a' },
  yellow:  { seed: '#e3b52a' },
  sky:     { seed: '#1f9fd6' },
  lime:    { seed: '#7aa82a' },
};

const nearest = (l) => STEPS.reduce((b, s) => Math.abs(L[s] - l) < Math.abs(L[b] - l) ? s : b, STEPS[0]);

const out = {};
for (const [name, r] of Object.entries(RAMPS)) {
  const seed = oklch(r.seed);
  const peak = r.chroma ?? seed.c;
  const ramp = {};
  for (const s of STEPS) {
    const col = clampChroma({ mode: 'oklch', l: L[s], c: peak * C[s], h: seed.h }, 'oklch');
    ramp[s] = formatHex(col);
  }
  for (const hex of Object.keys(r.pin ?? {})) {
    let s = nearest(oklch(hex).l);
    // two pins can land on one step: push the second to the next free step in its direction
    while (Object.values(out[name + '__pins'] ?? {}).includes(s)) s = STEPS[STEPS.indexOf(s) + (oklch(hex).l < L[s] ? 1 : -1)];
    ramp[s] = hex;
    (out[name + '__pins'] ??= {})[hex] = s;
  }
  out[name] = ramp;
}
const pins = {};
for (const k of Object.keys(out)) if (k.endsWith('__pins')) { pins[k.slice(0, -6)] = out[k]; delete out[k]; }

writeFileSync(new URL('../tokens/palette.json', import.meta.url), JSON.stringify({ $description: 'Generated by scripts/palette.mjs. Palette steps are never used by components directly.', pins, ramps: out }, null, 2) + '\n');
for (const [n, ramp] of Object.entries(out)) console.log(n.padEnd(8), STEPS.map((s) => `${s}:${ramp[s]}(${wcagContrast(ramp[s], '#ffffff').toFixed(1)})`).join(' '));
console.log(pins);
